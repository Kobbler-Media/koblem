<script lang="ts">
  import { onMount } from 'svelte';
  import { listReviewSessions, getReviewSession, replayReviewSession } from '#lib/api/client.ts';
  import type {
    ReviewSessionSummary,
    ReviewSessionDetail,
    ReviewResponse,
    SamplingConfig
  } from '#lib/types.ts';
  import JsonBlock from '#lib/components/JsonBlock.svelte';

  let sessions = $state<ReviewSessionSummary[]>([]);
  let loading = $state(true);
  let error = $state('');
  let expandedId = $state<string | null>(null);
  let detail = $state<ReviewSessionDetail | null>(null);
  let detailLoading = $state(false);
  let detailError = $state('');
  let showPrompt = $state(false);
  let showThinking = $state(false);

  /// In-progress and completed replay results, keyed by session id.
  let replayLoading = $state<string | null>(null);
  let replayError = $state('');
  let replayResult = $state<ReviewResponse | null>(null);
  /// JSON snippet generated by "Save as scenario" — shown in a textarea for
  /// the user to copy + paste into testbed.rs.
  let scenarioExport = $state('');

  onMount(async () => {
    try {
      sessions = await listReviewSessions(50);
    } catch (e) {
      error = e instanceof Error ? e.message : 'Failed to load sessions';
    }
    loading = false;

    const params = new URLSearchParams(window.location.search);
    const requested = params.get('session');
    if (requested) {
      await toggleRow(requested);
      queueMicrotask(() => {
        document.getElementById(`session-${requested}`)?.scrollIntoView({ block: 'start' });
      });
    }
  });

  async function toggleRow(id: string) {
    if (expandedId === id) {
      expandedId = null;
      detail = null;
      replayResult = null;
      replayError = '';
      scenarioExport = '';
      return;
    }
    expandedId = id;
    detail = null;
    replayResult = null;
    replayError = '';
    scenarioExport = '';
    detailLoading = true;
    detailError = '';
    showPrompt = false;
    showThinking = false;
    try {
      detail = await getReviewSession(id);
    } catch (e) {
      detailError = e instanceof Error ? e.message : 'Failed to load session';
    }
    detailLoading = false;
  }

  async function handleReplay(id: string) {
    replayLoading = id;
    replayError = '';
    replayResult = null;
    try {
      const resp = await replayReviewSession(id);
      replayResult = resp.fresh;
    } catch (e) {
      replayError = e instanceof Error ? e.message : 'Replay failed';
    }
    replayLoading = null;
  }

  /// Build a Rust `TestScenario { ... }` literal from the currently expanded
  /// session detail and stuff it into `scenarioExport` for the user to copy.
  /// The id/name placeholders use the session UUID prefix; the user is
  /// expected to rename them before pasting into testbed.rs.
  function exportAsScenario() {
    if (!detail) return;
    const req: any = detail.request ?? {};
    const candidates: any[] = req.candidates ?? [];
    const idShort = detail.id.slice(0, 8);
    // expected_actions covers releases that were either kobload-accepted
    // (we'll ask the user to verify whether they should still be accepted)
    // or were promoted by the LLM in the original run. The user prunes
    // before pasting.
    const llmAccepts: Set<string> = new Set();
    if (detail.verdicts && typeof detail.verdicts === 'object') {
      const v: any = detail.verdicts;
      for (const d of v.agreed ?? []) llmAccepts.add(d.name);
      for (const d of v.promoted ?? []) llmAccepts.add(d.name);
    }
    const expectedRows = candidates
      .filter((c: any) => c.kobload_accepted || llmAccepts.has(c.name))
      .map((c: any) => {
        const expected = llmAccepts.has(c.name) ? 'accept' : 'reject';
        return `                ExpectedAction { release_name: ${JSON.stringify(c.name)}, expected: ${JSON.stringify(expected)}, reason: "TODO: explain" },`;
      })
      .join('\n');

    scenarioExport = `// Paste into testbed.rs build_scenarios(). Rename id/name as needed,
// review the expected actions before committing.
TestScenario {
    id: "session-${idShort}",
    name: ${JSON.stringify(`Replay of session ${idShort}`)},
    description: "Imported from history session ${detail.id}.",
    category: "imported",
    expected_actions: vec![
${expectedRows}
    ],
    request: serde_json::from_str::<ReviewRequest>(r#####"
${JSON.stringify(detail.request, null, 2)}
"#####).expect("valid request JSON"),
},`;
  }

  function copyExport() {
    if (scenarioExport) {
      navigator.clipboard?.writeText(scenarioExport);
    }
  }

  function formatDate(iso: string): string {
    const d = new Date(iso);
    return d.toLocaleString();
  }

  /// Parse the stored `prompt_sent` debug string back into discrete role
  /// messages. Format mirrors the Rust `format_debug_prompt` writer:
  /// `[role]\n<content>` segments joined by a `\n\n---\n\n` divider. Anything
  /// that doesn't match is dropped — we only need system + user for chat.
  function parsePromptSent(promptSent: string): { system: string; user: string } {
    const segments = promptSent.split('\n\n---\n\n');
    let system = '';
    let user = '';
    for (const seg of segments) {
      const m = seg.match(/^\[(\w+)\]\n([\s\S]*)$/);
      if (!m) continue;
      const role = m[1];
      const content = m[2];
      if (role === 'system') system = content;
      else if (role === 'user') user = content;
    }
    return { system, user };
  }

  /// Open the current detail's prompt in the Chat page. Best-effort sampling
  /// reproduction: structured-review baseline (Deterministic preset, thinking
  /// off — matches `review_pipeline::baseline`) overlaid with whatever the
  /// original request set under `sampling`. The chat page reads the prefill
  /// from sessionStorage and clears it after consuming.
  function openInChat() {
    if (!detail) return;
    const { system, user } = parsePromptSent(detail.prompt_sent ?? '');
    const requestSampling: Partial<SamplingConfig> =
      (detail.request as { sampling?: SamplingConfig })?.sampling ?? {};
    const sampling: SamplingConfig = {
      sampling_preset: 'deterministic',
      enable_thinking: false,
      ...requestSampling
    };
    sessionStorage.setItem(
      'koblem-chat-prefill',
      JSON.stringify({ system, prompt: user, sampling })
    );
    window.location.href = '/chat';
  }
</script>

